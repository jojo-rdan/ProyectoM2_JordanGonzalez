USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA ANALYTICS;

CREATE TABLE IF NOT EXISTS FACT_DELIVERIES (

    -- Clave sustituta de la tabla de hechos
    DELIVERY_KEY NUMBER(38,0)
        IDENTITY(1,1) PRIMARY KEY,

    -- Identificadores del sistema operacional
    DELIVERY_ID NUMBER(38,0) NOT NULL,
    TRIP_ID NUMBER(38,0) NOT NULL,
    TRACKING_NUMBER VARCHAR(100),

    -- Claves del modelo dimensional
    DATE_KEY NUMBER(8,0) NOT NULL,
    TIME_KEY NUMBER(2,0) NOT NULL,
    VEHICLE_KEY NUMBER(38,0) NOT NULL,
    DRIVER_KEY NUMBER(38,0) NOT NULL,
    ROUTE_KEY NUMBER(38,0) NOT NULL,
    CUSTOMER_KEY NUMBER(38,0) NOT NULL,

    -- Fechas operacionales
    DEPARTURE_DATETIME TIMESTAMP_NTZ NOT NULL,
    SCHEDULED_DATETIME TIMESTAMP_NTZ NOT NULL,
    DELIVERED_DATETIME TIMESTAMP_NTZ NOT NULL,

    -- Métricas de la entrega
    DELIVERY_COUNT NUMBER(1,0) NOT NULL DEFAULT 1,
    PACKAGE_WEIGHT_KG NUMBER(18,3) NOT NULL,
    DELIVERY_DURATION_MINUTES NUMBER(18,3) NOT NULL,
    SCHEDULE_VARIANCE_MINUTES NUMBER(18,3) NOT NULL,
    IS_ON_TIME BOOLEAN NOT NULL,

    -- Métricas asignadas desde el viaje
    ALLOCATED_DISTANCE_KM NUMBER(20,6) NOT NULL,
    ALLOCATED_FUEL_LITERS NUMBER(20,6) NOT NULL,
    ALLOCATION_METHOD VARCHAR(50)
        NOT NULL DEFAULT 'WEIGHT_PROPORTIONAL_V1',

    -- Métrica financiera sintética
    ESTIMATED_REVENUE_COP NUMBER(18,2),
    REVENUE_POLICY_VERSION VARCHAR(50),

    -- Auditoría e idempotencia
    SOURCE_ROW_HASH VARCHAR(64) NOT NULL,
    DW_LOADED_AT TIMESTAMP_NTZ
        DEFAULT CURRENT_TIMESTAMP(),
    DW_UPDATED_AT TIMESTAMP_NTZ
        DEFAULT CURRENT_TIMESTAMP(),

    -- Relaciones dimensionales
    FOREIGN KEY (DATE_KEY)
        REFERENCES DIM_DATE(DATE_KEY),

    FOREIGN KEY (TIME_KEY)
        REFERENCES DIM_TIME(TIME_KEY),

    FOREIGN KEY (VEHICLE_KEY)
        REFERENCES DIM_VEHICLE(VEHICLE_KEY),

    FOREIGN KEY (DRIVER_KEY)
        REFERENCES DIM_DRIVER(DRIVER_KEY),

    FOREIGN KEY (ROUTE_KEY)
        REFERENCES DIM_ROUTE(ROUTE_KEY),

    FOREIGN KEY (CUSTOMER_KEY)
        REFERENCES DIM_CUSTOMER(CUSTOMER_KEY)
);
