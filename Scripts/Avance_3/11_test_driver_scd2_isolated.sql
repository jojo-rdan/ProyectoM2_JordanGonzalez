-- FleetLogix Avance #3: prueba SCD tipo 2 totalmente aislada.
-- No actualiza ANALYTICS.DIM_DRIVER, ANALYTICS.FACT_DELIVERIES ni PostgreSQL.
-- Ejecutar TODO en una misma hoja/sesion de Snowflake (Snowsight).
-- Reproduce las operaciones UPDATE + INSERT de SCD2 con nombres temporales.
-- NOTA: al ser una copia CTAS, la nueva clave sustituta se asigna manualmente
-- SOLO en la prueba; no se comprueba la secuencia IDENTITY del cargador real.

USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA STAGING;
ALTER SESSION SET TIMEZONE = 'UTC';

-- 1. Fotografia aislada de UN conductor real; la tabla real es solo lectura.
CREATE TEMPORARY TABLE STAGING.TMP_SCD2_DRIVER_HISTORY AS
SELECT *
FROM ANALYTICS.DIM_DRIVER
WHERE DRIVER_ID = (SELECT MIN(DRIVER_ID) FROM ANALYTICS.DIM_DRIVER);

-- 2. Simulacion de una nueva version de ese mismo conductor.
-- SHA2 produce un hash diferente a proposito: es un cambio SIMULADO.
-- No reproduce el calculo canonico JSON que realiza el transformador Python.
CREATE TEMPORARY TABLE STAGING.TMP_SCD2_DRIVER_INCOMING AS
SELECT
    DRIVER_ID,
    DRIVER_KEY AS PREVIOUS_DRIVER_KEY,
    EMPLOYEE_CODE,
    FIRST_NAME,
    LAST_NAME,
    LICENSE_EXPIRY,
    HIRE_DATE,
    'SCD2_TEST'::VARCHAR(30) AS DRIVER_STATUS,
    ASSIGNED_ZONE,
    SHA2(ATTRIBUTE_HASH || '|SCD2_TEST|', 256) AS ATTRIBUTE_HASH,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS CHANGED_AT
FROM STAGING.TMP_SCD2_DRIVER_HISTORY
WHERE IS_CURRENT = TRUE;

-- Punto de control inicial: debe ser 1 version vigente y 1 fila de entrada.
SELECT
    (SELECT COUNT(*) FROM STAGING.TMP_SCD2_DRIVER_HISTORY) AS VERSIONES_INICIALES,
    (SELECT COUNT(*) FROM STAGING.TMP_SCD2_DRIVER_INCOMING) AS FILAS_SIMULADAS,
    (SELECT COUNT(*) FROM ANALYTICS.DIM_DRIVER) AS DIM_DRIVER_REAL,
    (SELECT COUNT(*) FROM ANALYTICS.FACT_DELIVERIES) AS FACT_DELIVERIES_REAL;

-- 3. PRIMERA PASADA: cerrar version anterior si cambio el hash.
BEGIN TRANSACTION;

UPDATE STAGING.TMP_SCD2_DRIVER_HISTORY AS t
SET
    VALID_TO = s.CHANGED_AT,
    IS_CURRENT = FALSE
FROM STAGING.TMP_SCD2_DRIVER_INCOMING AS s
WHERE t.DRIVER_ID = s.DRIVER_ID
  AND t.IS_CURRENT = TRUE
  AND t.ATTRIBUTE_HASH IS DISTINCT FROM s.ATTRIBUTE_HASH;

-- La clave surrogate de la prueba se asigna expresamente para no usar
-- ni modificar una secuencia de la tabla productiva.
INSERT INTO STAGING.TMP_SCD2_DRIVER_HISTORY (
    DRIVER_KEY, DRIVER_ID, EMPLOYEE_CODE, FIRST_NAME, LAST_NAME,
    LICENSE_EXPIRY, HIRE_DATE, DRIVER_STATUS, ASSIGNED_ZONE,
    VALID_FROM, VALID_TO, IS_CURRENT, ATTRIBUTE_HASH, DW_LOADED_AT
)
SELECT
    s.PREVIOUS_DRIVER_KEY + 1000000,
    s.DRIVER_ID, s.EMPLOYEE_CODE, s.FIRST_NAME, s.LAST_NAME,
    s.LICENSE_EXPIRY, s.HIRE_DATE, s.DRIVER_STATUS, s.ASSIGNED_ZONE,
    s.CHANGED_AT, NULL, TRUE, s.ATTRIBUTE_HASH,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STAGING.TMP_SCD2_DRIVER_INCOMING AS s
WHERE NOT EXISTS (
    SELECT 1 FROM STAGING.TMP_SCD2_DRIVER_HISTORY AS cur
    WHERE cur.DRIVER_ID = s.DRIVER_ID AND cur.IS_CURRENT = TRUE
);

COMMIT;

-- Primera comprobacion: 2 versiones, una vigente, una historica.
SELECT
    'PRIMERA_PASADA' AS FASE,
    COUNT(*) AS VERSIONES,
    COUNT_IF(IS_CURRENT) AS ACTUALES,
    COUNT_IF(NOT IS_CURRENT) AS HISTORICAS,
    COUNT(DISTINCT DRIVER_KEY) AS KEYS_UNICAS,
    COUNT_IF(VALID_TO IS NOT NULL AND VALID_TO <= VALID_FROM)
      AS VIGENCIAS_INVALIDAS,
    COUNT_IF(IS_CURRENT AND VALID_TO IS NOT NULL)
      AS ACTUALES_CON_FECHA_FIN,
    COUNT_IF(NOT IS_CURRENT AND VALID_TO IS NULL)
      AS HISTORICAS_SIN_FIN
FROM STAGING.TMP_SCD2_DRIVER_HISTORY;

SELECT DRIVER_KEY, DRIVER_ID, DRIVER_STATUS, VALID_FROM, VALID_TO, IS_CURRENT
FROM STAGING.TMP_SCD2_DRIVER_HISTORY
ORDER BY VALID_FROM, DRIVER_KEY;

-- 4. SEGUNDA PASADA CON LA MISMA ENTRADA: no debe generar otra version.
BEGIN TRANSACTION;

UPDATE STAGING.TMP_SCD2_DRIVER_HISTORY AS t
SET
    VALID_TO = s.CHANGED_AT,
    IS_CURRENT = FALSE
FROM STAGING.TMP_SCD2_DRIVER_INCOMING AS s
WHERE t.DRIVER_ID = s.DRIVER_ID
  AND t.IS_CURRENT = TRUE
  AND t.ATTRIBUTE_HASH IS DISTINCT FROM s.ATTRIBUTE_HASH;

INSERT INTO STAGING.TMP_SCD2_DRIVER_HISTORY (
    DRIVER_KEY, DRIVER_ID, EMPLOYEE_CODE, FIRST_NAME, LAST_NAME,
    LICENSE_EXPIRY, HIRE_DATE, DRIVER_STATUS, ASSIGNED_ZONE,
    VALID_FROM, VALID_TO, IS_CURRENT, ATTRIBUTE_HASH, DW_LOADED_AT
)
SELECT
    s.PREVIOUS_DRIVER_KEY + 1000000,
    s.DRIVER_ID, s.EMPLOYEE_CODE, s.FIRST_NAME, s.LAST_NAME,
    s.LICENSE_EXPIRY, s.HIRE_DATE, s.DRIVER_STATUS, s.ASSIGNED_ZONE,
    s.CHANGED_AT, NULL, TRUE, s.ATTRIBUTE_HASH,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STAGING.TMP_SCD2_DRIVER_INCOMING AS s
WHERE NOT EXISTS (
    SELECT 1 FROM STAGING.TMP_SCD2_DRIVER_HISTORY AS cur
    WHERE cur.DRIVER_ID = s.DRIVER_ID AND cur.IS_CURRENT = TRUE
);

COMMIT;

-- Segunda comprobacion: los mismos conteos que la primera pasada.
SELECT
    'SEGUNDA_PASADA' AS FASE,
    COUNT(*) AS VERSIONES,
    COUNT_IF(IS_CURRENT) AS ACTUALES,
    COUNT_IF(NOT IS_CURRENT) AS HISTORICAS,
    COUNT(DISTINCT DRIVER_KEY) AS KEYS_UNICAS,
    COUNT_IF(VALID_TO IS NOT NULL AND VALID_TO <= VALID_FROM)
      AS VIGENCIAS_INVALIDAS,
    COUNT_IF(IS_CURRENT AND VALID_TO IS NOT NULL)
      AS ACTUALES_CON_FECHA_FIN,
    COUNT_IF(NOT IS_CURRENT AND VALID_TO IS NULL)
      AS HISTORICAS_SIN_FIN
FROM STAGING.TMP_SCD2_DRIVER_HISTORY;

-- Confirmar que las tablas REALES siguen intactas.
SELECT
    (SELECT COUNT(*) FROM ANALYTICS.DIM_DRIVER) AS DIM_DRIVER_REAL,
    (SELECT COUNT_IF(IS_CURRENT) FROM ANALYTICS.DIM_DRIVER)
      AS CONDUCTORES_ACTUALES_REALES,
    (SELECT COUNT(*) FROM ANALYTICS.FACT_DELIVERIES)
      AS FACT_DELIVERIES_REAL;

