-- FleetLogix / Avance 3: validación posterior a la política SYNTHETIC_REVENUE_V1
-- SOLO LECTURA. El origen carece de ingresos comerciales observados.
USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA ANALYTICS;

-- 1. Integridad, versión y conciliación con la simulación previa.
SELECT
    COUNT(*) AS TOTAL_ENTREGAS,
    COUNT(DISTINCT DELIVERY_ID) AS IDS_UNICOS,
    COUNT_IF(ESTIMATED_REVENUE_COP IS NULL) AS INGRESOS_NULOS,
    COUNT_IF(REVENUE_POLICY_VERSION IS NULL
        OR REVENUE_POLICY_VERSION <> 'SYNTHETIC_REVENUE_V1') AS POLITICAS_INVALIDAS,
    COUNT_IF(ESTIMATED_REVENUE_COP IS NOT NULL AND
        ESTIMATED_REVENUE_COP <> ROUND(
            7000 + PACKAGE_WEIGHT_KG * 20 + ALLOCATED_DISTANCE_KM * 300,
            2
        )) AS FORMULAS_INCONSISTENTES,
    ROUND(SUM(ESTIMATED_REVENUE_COP), 2) AS INGRESO_TOTAL_ESTIMADO_COP,
    ROUND(SUM(ALLOCATED_DISTANCE_KM), 6) AS DISTANCIA_TOTAL_KM,
    ROUND(SUM(ALLOCATED_FUEL_LITERS), 6) AS COMBUSTIBLE_TOTAL_L
FROM ANALYTICS.FACT_DELIVERIES;

-- 2. Perfil de los ingresos sintéticos (comparar con simulación aprobada).
SELECT
    ROUND(MIN(ESTIMATED_REVENUE_COP), 2) AS INGRESO_MIN_COP,
    ROUND(AVG(ESTIMATED_REVENUE_COP), 2) AS INGRESO_PROMEDIO_COP,
    ROUND(PERCENTILE_CONT(0.5) WITHIN GROUP
        (ORDER BY ESTIMATED_REVENUE_COP), 2) AS INGRESO_MEDIANA_COP,
    ROUND(PERCENTILE_CONT(0.95) WITHIN GROUP
        (ORDER BY ESTIMATED_REVENUE_COP), 2) AS INGRESO_P95_COP,
    ROUND(MAX(ESTIMATED_REVENUE_COP), 2) AS INGRESO_MAX_COP,
    COUNT_IF(ESTIMATED_REVENUE_COP > 100000) AS ENTREGAS_MAYORES_100K,
    COUNT_IF(ESTIMATED_REVENUE_COP > 250000) AS ENTREGAS_MAYORES_250K
FROM ANALYTICS.FACT_DELIVERIES;
