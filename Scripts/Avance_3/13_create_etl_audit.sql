
USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA CONTROL;

-- Registro general de cada ejecución del ETL.

CREATE TABLE IF NOT EXISTS ETL_RUNS (
    RUN_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    PIPELINE_NAME VARCHAR(100) NOT NULL,
    RUN_MODE VARCHAR(30) NOT NULL,

    STARTED_AT TIMESTAMP_LTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP(),

    FINISHED_AT TIMESTAMP_LTZ,

    STATUS VARCHAR(30) NOT NULL,

    ERROR_MESSAGE VARCHAR(2000),

    CREATED_BY VARCHAR(100)
);

-- Detalle de cada etapa dentro de una ejecución.

CREATE TABLE IF NOT EXISTS ETL_RUN_STEPS (
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_NAME VARCHAR(100) NOT NULL,

    STARTED_AT TIMESTAMP_LTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP(),

    FINISHED_AT TIMESTAMP_LTZ,

    STATUS VARCHAR(30) NOT NULL,

    ROWS_READ NUMBER(38,0),
    ROWS_INSERTED NUMBER(38,0),
    ROWS_UPDATED NUMBER(38,0),
    ROWS_REJECTED NUMBER(38,0),

    DETAILS VARIANT,

    FOREIGN KEY (RUN_ID)
        REFERENCES ETL_RUNS(RUN_ID)
);
