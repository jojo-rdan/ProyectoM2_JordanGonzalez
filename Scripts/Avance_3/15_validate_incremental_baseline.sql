-- FleetLogix · Validación de referencia tras la prueba de delta vacío.
-- SOLO SELECT: no modifica ANALYTICS ni CONTROL.
USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA ANALYTICS;

SELECT
    COUNT(*) AS TOTAL_ENTREGAS,
    COUNT(DISTINCT DELIVERY_ID) AS IDS_UNICOS,
    COUNT(DISTINCT TRIP_ID) AS VIAJES,
    ROUND(SUM(ALLOCATED_DISTANCE_KM), 6) AS DISTANCIA_KM,
    ROUND(SUM(ALLOCATED_FUEL_LITERS), 6) AS COMBUSTIBLE_L,
    ROUND(SUM(ESTIMATED_REVENUE_COP), 2) AS INGRESOS_SINTETICOS_COP,
    COUNT_IF(REVENUE_POLICY_VERSION <> 'SYNTHETIC_REVENUE_V1'
             OR REVENUE_POLICY_VERSION IS NULL) AS POLITICAS_INCORRECTAS
FROM ANALYTICS.FACT_DELIVERIES;
