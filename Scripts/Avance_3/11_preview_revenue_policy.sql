
USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA ANALYTICS;

-- Simulación de ingresos sintéticos
-- Política propuesta: SYNTHETIC_REVENUE_V1
-- No modifica ninguna tabla.

WITH ingresos_simulados AS (
    SELECT
        DELIVERY_ID,
        PACKAGE_WEIGHT_KG,
        ALLOCATED_DISTANCE_KM,

        ROUND(
            7000
            + (PACKAGE_WEIGHT_KG * 20)
            + (ALLOCATED_DISTANCE_KM * 300),
            2
        ) AS INGRESO_ESTIMADO_COP

    FROM FACT_DELIVERIES
)

SELECT
    COUNT(*) AS TOTAL_ENTREGAS,

    ROUND(MIN(INGRESO_ESTIMADO_COP), 2)
        AS INGRESO_MIN_COP,

    ROUND(AVG(INGRESO_ESTIMADO_COP), 2)
        AS INGRESO_PROMEDIO_COP,

    ROUND(
        PERCENTILE_CONT(0.5)
        WITHIN GROUP (ORDER BY INGRESO_ESTIMADO_COP),
        2
    ) AS INGRESO_MEDIANA_COP,

    ROUND(
        PERCENTILE_CONT(0.95)
        WITHIN GROUP (ORDER BY INGRESO_ESTIMADO_COP),
        2
    ) AS INGRESO_P95_COP,

    ROUND(MAX(INGRESO_ESTIMADO_COP), 2)
        AS INGRESO_MAX_COP,

    ROUND(SUM(INGRESO_ESTIMADO_COP), 2)
        AS INGRESO_TOTAL_ESTIMADO_COP,

    COUNT_IF(INGRESO_ESTIMADO_COP > 100000)
        AS ENTREGAS_MAYORES_100K,

    COUNT_IF(INGRESO_ESTIMADO_COP > 250000)
        AS ENTREGAS_MAYORES_250K,

    COUNT_IF(INGRESO_ESTIMADO_COP IS NULL)
        AS INGRESOS_NULOS

FROM ingresos_simulados;
