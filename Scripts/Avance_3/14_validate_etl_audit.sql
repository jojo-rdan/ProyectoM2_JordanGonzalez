USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;

-- Los últimos RUN_ID y estados registrados.
SELECT RUN_ID, PIPELINE_NAME, RUN_MODE, STATUS,
       STARTED_AT, FINISHED_AT, ERROR_MESSAGE
FROM CONTROL.ETL_RUNS
ORDER BY STARTED_AT DESC
LIMIT 5;

-- Pasos asociados a la ejecución más reciente.
SELECT STEP_NAME, STATUS, STARTED_AT, FINISHED_AT, DETAILS
FROM CONTROL.ETL_RUN_STEPS
WHERE RUN_ID = (
    SELECT RUN_ID FROM CONTROL.ETL_RUNS
    ORDER BY STARTED_AT DESC LIMIT 1
)
ORDER BY STARTED_AT, STEP_NAME;

-- Totales del historial de auditoría (sin presuponer otras ejecuciones).
SELECT
    (SELECT COUNT(*) FROM CONTROL.ETL_RUNS) AS TOTAL_RUNS,
    (SELECT COUNT(*) FROM CONTROL.ETL_RUN_STEPS) AS TOTAL_STEPS;
