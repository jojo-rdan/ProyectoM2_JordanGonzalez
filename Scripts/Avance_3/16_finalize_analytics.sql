USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA ANALYTICS;

-- Preagregado operativo: entregas por conductor, fecha y hora.
-- Se calcula por DRIVER_KEY para respetar versiones SCD2.
CREATE OR REPLACE TABLE ANALYTICS.AGG_DRIVER_HOURLY
COMMENT = 'Snapshot de agregación por conductor, fecha y hora; actualizar después del ETL'
AS
SELECT
    f.DATE_KEY,
    tm.HOUR_24 AS DELIVERY_HOUR,
    f.DRIVER_KEY,
    d.DRIVER_ID,
    COUNT(*) AS DELIVERIES,
    COUNT_IF(f.IS_ON_TIME) AS ON_TIME_DELIVERIES,
    SUM(f.PACKAGE_WEIGHT_KG) AS PACKAGE_WEIGHT_KG,
    SUM(f.DELIVERY_DURATION_MINUTES) AS DELIVERY_DURATION_MINUTES,
    SUM(f.ALLOCATED_DISTANCE_KM) AS ALLOCATED_DISTANCE_KM,
    SUM(f.ALLOCATED_FUEL_LITERS) AS ALLOCATED_FUEL_LITERS
FROM ANALYTICS.FACT_DELIVERIES f
JOIN ANALYTICS.DIM_TIME tm ON tm.TIME_KEY = f.TIME_KEY
JOIN ANALYTICS.DIM_DRIVER d ON d.DRIVER_KEY = f.DRIVER_KEY
GROUP BY f.DATE_KEY, tm.HOUR_24, f.DRIVER_KEY, d.DRIVER_ID;

-- Preagregado mensual por ruta. Los ingresos son FICTICIOS.
CREATE OR REPLACE TABLE ANALYTICS.AGG_MONTHLY_ROUTE
COMMENT = 'Snapshot mensual por ruta; ingresos sinteticos no son facturacion'
AS
SELECT
    DATE_TRUNC('MONTH', TO_DATE(TO_VARCHAR(f.DATE_KEY), 'YYYYMMDD'))::DATE AS MONTH_START,
    f.ROUTE_KEY,
    r.ROUTE_ID,
    r.ROUTE_CODE,
    r.ORIGIN_CITY,
    r.DESTINATION_CITY,
    COUNT(*) AS DELIVERIES,
    COUNT(DISTINCT f.TRIP_ID) AS DISTINCT_TRIPS,
    COUNT_IF(f.IS_ON_TIME) AS ON_TIME_DELIVERIES,
    SUM(f.ALLOCATED_DISTANCE_KM) AS ALLOCATED_DISTANCE_KM,
    SUM(f.ALLOCATED_FUEL_LITERS) AS ALLOCATED_FUEL_LITERS,
    SUM(f.ESTIMATED_REVENUE_COP) AS ESTIMATED_REVENUE_COP,
    'SYNTHETIC_REVENUE_V1' AS REVENUE_POLICY_VERSION
FROM ANALYTICS.FACT_DELIVERIES f
JOIN ANALYTICS.DIM_ROUTE r ON r.ROUTE_KEY = f.ROUTE_KEY
GROUP BY 1,2,3,4,5,6;

-- Vista segura OPERATIONS: incluye datos operativos del cliente para entrega; requiere rol restringido.
CREATE OR REPLACE SECURE VIEW ANALYTICS.VW_OPERATIONS_DELIVERIES
COMMENT = 'Vista operativa restringida, incluye destino del cliente pero no ingresos'
AS
SELECT
    f.DELIVERY_ID, f.TRIP_ID, f.DATE_KEY,
    tm.HOUR_24 AS DELIVERY_HOUR,
    d.DRIVER_ID, v.VEHICLE_ID,
    f.CUSTOMER_KEY, c.CUSTOMER_NAME, c.DELIVERY_ADDRESS,
    v.VEHICLE_TYPE,
    r.ROUTE_CODE, r.ORIGIN_CITY, r.DESTINATION_CITY,
    f.SCHEDULED_DATETIME, f.DELIVERED_DATETIME,
    f.DELIVERY_COUNT, f.PACKAGE_WEIGHT_KG,
    f.DELIVERY_DURATION_MINUTES, f.SCHEDULE_VARIANCE_MINUTES,
    f.IS_ON_TIME, f.ALLOCATED_DISTANCE_KM, f.ALLOCATED_FUEL_LITERS
FROM ANALYTICS.FACT_DELIVERIES f
JOIN ANALYTICS.DIM_TIME tm ON tm.TIME_KEY = f.TIME_KEY
JOIN ANALYTICS.DIM_DRIVER d ON d.DRIVER_KEY = f.DRIVER_KEY
JOIN ANALYTICS.DIM_VEHICLE v ON v.VEHICLE_KEY = f.VEHICLE_KEY
JOIN ANALYTICS.DIM_ROUTE r ON r.ROUTE_KEY = f.ROUTE_KEY
JOIN ANALYTICS.DIM_CUSTOMER c ON c.CUSTOMER_KEY = f.CUSTOMER_KEY;

-- Vista segura SALES: únicamente agregados; ingresos explícitamente ficticios.
CREATE OR REPLACE SECURE VIEW ANALYTICS.VW_SALES_MONTHLY_REVENUE
COMMENT = 'Vista financiera agregada; ingresos sinteticos, no facturacion real'
AS
SELECT
    MONTH_START,
    ROUTE_CODE, ORIGIN_CITY, DESTINATION_CITY,
    DELIVERIES,
    ON_TIME_DELIVERIES,
    ESTIMATED_REVENUE_COP,
    REVENUE_POLICY_VERSION
FROM ANALYTICS.AGG_MONTHLY_ROUTE;

