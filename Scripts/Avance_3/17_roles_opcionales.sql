-- SEGREGACIÓN SALES / OPERATIONS — ejecutar por separado con ACCOUNTADMIN.
-- Crea roles y derechos mínimos sobre VISTAS, NO sobre FACT ni DIM.
-- NO asigna roles a usuarios automáticamente ni los entrega a PUBLIC.
-- Si el proyecto se entrega solo como demostración, basta documentar este SQL.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS FLEETLOGIX_OPERATIONS_ROLE;
CREATE ROLE IF NOT EXISTS FLEETLOGIX_SALES_ROLE;

GRANT USAGE ON WAREHOUSE FLEETLOGIX_WH TO ROLE FLEETLOGIX_OPERATIONS_ROLE;
GRANT USAGE ON DATABASE FLEETLOGIX_DWH TO ROLE FLEETLOGIX_OPERATIONS_ROLE;
GRANT USAGE ON SCHEMA FLEETLOGIX_DWH.ANALYTICS TO ROLE FLEETLOGIX_OPERATIONS_ROLE;
GRANT SELECT ON VIEW FLEETLOGIX_DWH.ANALYTICS.VW_OPERATIONS_DELIVERIES
TO ROLE FLEETLOGIX_OPERATIONS_ROLE;

GRANT USAGE ON WAREHOUSE FLEETLOGIX_WH TO ROLE FLEETLOGIX_SALES_ROLE;
GRANT USAGE ON DATABASE FLEETLOGIX_DWH TO ROLE FLEETLOGIX_SALES_ROLE;
GRANT USAGE ON SCHEMA FLEETLOGIX_DWH.ANALYTICS TO ROLE FLEETLOGIX_SALES_ROLE;
GRANT SELECT ON VIEW FLEETLOGIX_DWH.ANALYTICS.VW_SALES_MONTHLY_REVENUE
TO ROLE FLEETLOGIX_SALES_ROLE;

