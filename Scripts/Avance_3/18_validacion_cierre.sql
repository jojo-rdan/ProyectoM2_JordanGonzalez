USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA ANALYTICS;

-- 1) Tres indicadores críticos: 400000, 400000, 6270850032.24
SELECT
  COUNT(*) AS ENTREGAS,
  COUNT(DISTINCT DELIVERY_ID) AS ENTREGAS_UNICAS,
  ROUND(SUM(ESTIMATED_REVENUE_COP), 2) AS INGRESOS_SINTETICOS_COP,
  ROUND(SUM(ALLOCATED_DISTANCE_KM),6) AS DISTANCIA_KM,
  ROUND(SUM(ALLOCATED_FUEL_LITERS),6) AS COMBUSTIBLE_L
FROM ANALYTICS.FACT_DELIVERIES;

-- 2) Agregados: 400000 en ambos; ingreso mensual-ruta = ingreso hechos
SELECT
  (SELECT SUM(DELIVERIES) FROM ANALYTICS.AGG_DRIVER_HOURLY) AS AGG_OPERATIONS_DELIVERIES,
  (SELECT SUM(DELIVERIES) FROM ANALYTICS.AGG_MONTHLY_ROUTE) AS AGG_MONTHLY_DELIVERIES,
  (SELECT ROUND(SUM(ESTIMATED_REVENUE_COP),2) FROM ANALYTICS.AGG_MONTHLY_ROUTE) AS AGG_REVENUE_COP,
  (SELECT COUNT(*) FROM ANALYTICS.VW_OPERATIONS_DELIVERIES) AS SECURE_OPERATIONS_ROWS,
  (SELECT SUM(DELIVERIES) FROM ANALYTICS.VW_SALES_MONTHLY_REVENUE) AS SECURE_SALES_DELIVERIES;

-- 3) Definiciones de vistas: IS_SECURE debe ser YES/TRUE según el cliente.
SELECT TABLE_NAME, IS_SECURE
FROM FLEETLOGIX_DWH.INFORMATION_SCHEMA.VIEWS
WHERE TABLE_SCHEMA = 'ANALYTICS'
  AND TABLE_NAME IN ('VW_OPERATIONS_DELIVERIES','VW_SALES_MONTHLY_REVENUE')
ORDER BY TABLE_NAME;

-- 4) Último pipeline auditado.
SELECT RUN_MODE, STATUS, STARTED_AT, FINISHED_AT, RUN_ID
FROM FLEETLOGIX_DWH.CONTROL.ETL_RUNS
ORDER BY STARTED_AT DESC
LIMIT 5;

-- 5) Retención configurada en la base. No modificar si no se confirma edición.
SHOW PARAMETERS LIKE 'DATA_RETENTION_TIME_IN_DAYS' IN DATABASE FLEETLOGIX_DWH;
