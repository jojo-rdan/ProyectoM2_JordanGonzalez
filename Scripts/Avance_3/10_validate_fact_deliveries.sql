-- FleetLogix Avance #3 — controles tras cargar FACT_DELIVERIES.
-- No modifica datos. Ejecutar en Snowsight después de observar COMMIT.
USE ROLE SYSADMIN;
USE WAREHOUSE FLEETLOGIX_WH;
USE DATABASE FLEETLOGIX_DWH;
USE SCHEMA ANALYTICS;

-- (1) Esperado: 400000 filas, 400000 IDs únicos, 100000 viajes,
-- 0 sin clave, 0 ingresos sintéticos (política pendiente).
SELECT
    COUNT(*) AS ENTREGAS,
    COUNT(DISTINCT DELIVERY_ID) AS DELIVERY_ID_UNICOS,
    COUNT(DISTINCT TRIP_ID) AS VIAJES,
    COUNT_IF(
        DATE_KEY IS NULL OR TIME_KEY IS NULL OR VEHICLE_KEY IS NULL
        OR DRIVER_KEY IS NULL OR ROUTE_KEY IS NULL OR CUSTOMER_KEY IS NULL
    ) AS SIN_CLAVE_DIMENSIONAL,
    COUNT_IF(ESTIMATED_REVENUE_COP IS NOT NULL
             OR REVENUE_POLICY_VERSION IS NOT NULL) AS INGRESOS_SIN_POLITICA
FROM FACT_DELIVERIES;

-- (2) Conciliación esperada: 4701486.980000 km y 633064.820000 L.
SELECT
    SUM(DELIVERY_COUNT) AS ENTREGAS_MEDIDA,
    SUM(PACKAGE_WEIGHT_KG) AS PESO_TOTAL_KG,
    SUM(ALLOCATED_DISTANCE_KM) AS DISTANCIA_ASIGNADA_KM,
    SUM(ALLOCATED_FUEL_LITERS) AS COMBUSTIBLE_ASIGNADO_L
FROM FACT_DELIVERIES;

-- (3) Debe devolver cero filas: ninguna entrega duplicada.
SELECT DELIVERY_ID, COUNT(*) AS REPETICIONES
FROM FACT_DELIVERIES
GROUP BY DELIVERY_ID
HAVING COUNT(*) > 1
LIMIT 10;

-- (4) Esperado: todos los conteos de 'sin dimension' = 0.
-- El historial del conductor es un atributo de validez técnica; la relación
-- con su versión se comprueba por DRIVER_KEY, no por el conductor actual.
SELECT
    COUNT_IF(dt.DATE_KEY IS NULL) AS SIN_FECHA,
    COUNT_IF(tm.TIME_KEY IS NULL) AS SIN_HORA,
    COUNT_IF(v.VEHICLE_KEY IS NULL) AS SIN_VEHICULO,
    COUNT_IF(dr.DRIVER_KEY IS NULL) AS SIN_CONDUCTOR,
    COUNT_IF(rt.ROUTE_KEY IS NULL) AS SIN_RUTA,
    COUNT_IF(cu.CUSTOMER_KEY IS NULL) AS SIN_CLIENTE
FROM FACT_DELIVERIES f
LEFT JOIN DIM_DATE dt ON dt.DATE_KEY=f.DATE_KEY
LEFT JOIN DIM_TIME tm ON tm.TIME_KEY=f.TIME_KEY
LEFT JOIN DIM_VEHICLE v ON v.VEHICLE_KEY=f.VEHICLE_KEY
LEFT JOIN DIM_DRIVER dr ON dr.DRIVER_KEY=f.DRIVER_KEY
LEFT JOIN DIM_ROUTE rt ON rt.ROUTE_KEY=f.ROUTE_KEY
LEFT JOIN DIM_CUSTOMER cu ON cu.CUSTOMER_KEY=f.CUSTOMER_KEY;
